/**
 * Claude-д өгөх system prompt-ыг угсарна.
 * Агуулга нь тогтмол учир prompt caching-д бүрэн тохиромжтой.
 * @returns {Promise<string>}
 */
export async function buildSystemPrompt() {
  const { text } = await loadKnowledge();
  const knowledge = text || '(Мэдлэгийн сан хоосон байна — knowledge/ хавтсанд .md файл нэм.)';

  return [
    PERSONA,
    FLOW,
    MONEY_RULES,
    RULES,
    `# Хөтөлбөр ба ЭЕШ-ийн босго оноо\n\n${programListText()}`,
    `# Сургуулийн баримт мэдээлэл\n\n${knowledge}`,
  ].join('\n\n');
}

